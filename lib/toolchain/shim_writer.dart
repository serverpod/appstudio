import 'dart:io';

import 'package:path/path.dart' as p;

import '../feature_flags.dart';
import 'tool_status.dart';
import 'toolchain.dart';

/// Generates `~/Library/Application Support/App Studio/bin/*`.
///
/// Wrappers, not symlinks: a symlink cannot set `FLUTTER_ROOT`,
/// `GIT_EXEC_PATH` or `DYLD_LIBRARY_PATH`, and those are what make the tools
/// work outside App Studio.
///
/// No `python3` or `jq` anywhere — on a Mac without Xcode CLT, `/usr/bin/python3`
/// is a stub that prompts to install developer tools, which is the exact
/// failure this whole feature exists to avoid.
class ShimWriter {
  const ShimWriter({required this.binDir});

  final String binDir;

  /// Commands we expose, and the tool each comes from.
  static const _commands = <String, ToolId>{
    'flutter': ToolId.flutter,
    'dart': ToolId.flutter,
    'serverpod': ToolId.serverpodCli,
    'opencode': ToolId.opencode,
    'git': ToolId.git,
  };

  /// Commands this build does not expose. They stay in [_commands] so
  /// [removeAll] still sweeps them — a shim left by a build that did write one
  /// would otherwise outlive the feature.
  static const _skipped = <String>{
    if (!kOpenCodeAgentEnabled) 'opencode',
  };

  /// Rewrites every shim for [toolchain]. Safe to call repeatedly.
  Future<void> write(Toolchain toolchain) async {
    final dir = Directory(binDir);
    await dir.create(recursive: true);

    for (final entry in _commands.entries) {
      final file = File(p.join(binDir, entry.key));
      if (_skipped.contains(entry.key)) {
        // Reaped rather than skipped. The shim a previous build wrote would
        // otherwise sit here telling the user to install a tool that no longer
        // appears in Settings → Tools.
        if (await file.exists()) await file.delete();
        continue;
      }
      await file.writeAsString(_script(entry.key, entry.value, toolchain));
      await Process.run('/bin/chmod', ['755', file.path]);
    }
  }

  Future<void> removeAll() async {
    for (final command in _commands.keys) {
      final file = File(p.join(binDir, command));
      if (await file.exists()) await file.delete();
    }
  }

  String _script(String command, ToolId id, Toolchain toolchain) {
    final target = switch (command) {
      'dart' => toolchain.dartExecutable,
      'flutter' => toolchain.flutterExecutable,
      'serverpod' => toolchain.serverpodExecutable,
      'opencode' => toolchain.opencodeExecutable,
      'git' => toolchain.gitExecutable,
      _ => null,
    };

    final buffer = StringBuffer('#!/bin/sh\n')
      ..writeln('# Generated by App Studio. Edits will be overwritten.')
      ..writeln();

    if (target == null) {
      // A missing tool gets a shim that explains itself, rather than a
      // confusing "no such file or directory" from the shell.
      buffer
        ..writeln('echo "App Studio: $command is not installed." >&2')
        ..writeln(
          'echo "Open App Studio → Settings → Tools to install it." >&2',
        )
        ..writeln('exit 127');
      return buffer.toString();
    }

    final flutterRoot = toolchain.flutterRoot;
    final engineVersion =
        toolchain.resolvedTool(ToolId.flutter)?.facts['engineVersion'];
    final gitExecPath =
        toolchain.resolvedTool(ToolId.git)?.facts['gitExecPath'];
    final libDir =
        toolchain.resolvedTool(ToolId.serverpodCli)?.facts['libDir'];

    buffer.writeln('if [ ! -x "$target" ]; then');
    buffer.writeln(
      '  echo "App Studio: $command is no longer installed." >&2',
    );
    buffer.writeln('  exit 127');
    buffer.writeln('fi');
    buffer.writeln();

    if (flutterRoot != null) {
      buffer.writeln('export FLUTTER_ROOT="$flutterRoot"');
      buffer.writeln(
        'if [ -d "$flutterRoot/bin/cache/dart-sdk" ]; then',
      );
      buffer.writeln('  export DART_SDK="$flutterRoot/bin/cache/dart-sdk"');
      buffer.writeln('fi');
    }
    if (engineVersion != null && engineVersion.isNotEmpty) {
      buffer.writeln('export FLUTTER_PREBUILT_ENGINE_VERSION="$engineVersion"');
    }
    if (gitExecPath != null && gitExecPath.isNotEmpty) {
      buffer.writeln('export GIT_EXEC_PATH="$gitExecPath"');
    }
    if (id == ToolId.serverpodCli && libDir != null && libDir.isNotEmpty) {
      buffer.writeln(
        'export DYLD_LIBRARY_PATH="$libDir\${DYLD_LIBRARY_PATH:+:\$DYLD_LIBRARY_PATH}"',
      );
    }

    // Keep our git and native tools ahead of the /usr/bin CLT stubs.
    final pathPrefix = toolchain.binPathPrefix;
    if (pathPrefix.isNotEmpty) {
      buffer.writeln('export PATH="${pathPrefix.join(':')}:\$PATH"');
    }

    buffer
      ..writeln()
      ..writeln('exec "$target" "\$@"');
    return buffer.toString();
  }
}
